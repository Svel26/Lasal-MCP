import { mkdirSync, readFileSync, writeFileSync } from "fs";
import { dirname, resolve } from "path";
import { fileURLToPath } from "url";
import { createPilotRegistry } from "../core/actions/pilotCatalog.js";
import type { ActionRegistry } from "../core/actions/registry.js";
import { actionJsonSchema } from "../core/actions/schema.js";
import type { AnyActionDefinition, Domain } from "../core/actions/types.js";

interface JsonSchemaProperty {
  type?: string;
  description?: string;
  enum?: unknown[];
  items?: { type?: string };
  oneOf?: JsonSchemaProperty[];
  anyOf?: JsonSchemaProperty[];
}

interface JsonSchema {
  type?: string;
  properties?: Record<string, JsonSchemaProperty>;
  required?: string[];
}

const DOMAIN_ORDER: Domain[] = ["core", "class2", "visu", "screen", "lars", "deploy"];
const DOMAIN_TITLES: Record<Domain, string> = {
  core: "Core / Project",
  class2: "CLASS 2",
  visu: "VISUDesigner",
  screen: "LASAL SCREEN",
  lars: "LARS",
  deploy: "Deploy / MachineManager",
};

function escapeCell(value: string): string {
  return value.replace(/\|/g, "\\|").replace(/\r?\n/g, " ");
}

function schemaType(property: JsonSchemaProperty): string {
  if (property.enum?.length) return `enum: ${property.enum.map(String).join(", ")}`;
  if (property.type === "array") return `array<${property.items?.type ?? "unknown"}>`;
  if (property.oneOf?.length || property.anyOf?.length) {
    const variants = property.oneOf ?? property.anyOf ?? [];
    return variants.map((variant) => variant.type ?? "unknown").join(" | ");
  }
  return property.type ?? "unknown";
}

function renderParams(action: AnyActionDefinition): string[] {
  const schema = actionJsonSchema(action) as JsonSchema | undefined;
  const properties = schema?.properties ?? {};
  const required = new Set(schema?.required ?? []);
  const names = Object.keys(properties);
  if (names.length === 0) return ["_No parameters._"];

  const rows = [
    "| Param | Type | Required | Description |",
    "|---|---|---|---|",
    ...names.map((name) => {
      const property = properties[name] ?? {};
      const description = escapeCell(property.description ?? "");
      return `| \`${name}\` | ${escapeCell(schemaType(property))} | ${required.has(name) ? "yes" : "no"} | ${description} |`;
    }),
  ];
  return rows;
}

function renderExample(action: AnyActionDefinition, index: number): string[] {
  const example = action.examples[index];
  if (!example) return [];
  const payload: Record<string, unknown> = {
    action: action.id,
    params: example.params,
    ...(action.requiresConfirm ? { confirm: true } : {}),
  };
  return [
    `**Example${action.examples.length > 1 ? ` ${index + 1}` : ""}${example.note ? ` — ${example.note}` : ""}**`,
    "",
    "```json",
    JSON.stringify(payload, null, 2),
    "```",
  ];
}

export function renderActionsDoc(registry: ActionRegistry = createPilotRegistry()): string {
  const actions = registry.list({ includeExpert: true });
  const lines: string[] = [
    "# LASAL Action Catalog",
    "",
    "> Generated from the action registry. Do not edit this file by hand; run `npm run docs:actions`.",
    "",
    `**Total actions:** ${actions.length}`,
    "",
    "## Contents",
    "",
    ...DOMAIN_ORDER.map((domain) => {
      const count = actions.filter((action) => action.domain === domain).length;
      return `- [${DOMAIN_TITLES[domain]}](#${DOMAIN_TITLES[domain]
        .toLowerCase()
        .replace(/[^a-z0-9]+/g, "-")
        .replace(/^-|-$/g, "")}) — ${count}`;
    }),
    "",
  ];

  for (const domain of DOMAIN_ORDER) {
    const domainActions = actions.filter((action) => action.domain === domain);
    if (domainActions.length === 0) continue;
    lines.push(`## ${DOMAIN_TITLES[domain]}`, "");
    for (const action of domainActions) {
      lines.push(`### \`${action.id}\``, "", action.description ?? action.summary, "");
      lines.push(
        `- **Aliases:** ${action.aliases.length ? action.aliases.map((alias) => `\`${alias}\``).join(", ") : "—"}`,
        `- **Risk:** ${action.risk}`,
        `- **Confirmation:** ${action.requiresConfirm ? "required (`confirm=true`)" : "not required"}`,
        `- **Project:** ${action.requiresProject ? "required" : "optional"}`,
        `- **Async:** ${action.asyncCapable ? "supported" : "not supported"}`,
        `- **Dry run:** ${action.dryRunSupported ? "supported" : "not supported"}`,
        ...(action.expert ? ["- **Expert:** yes (requires `--allow-expert`)"] : []),
        `- **Tags:** ${action.tags.map((tag) => `\`${tag}\``).join(", ")}`,
        "",
      );

      if (action.hints?.length) {
        lines.push("**Hints**", "", ...action.hints.map((hint) => `- ${hint}`), "");
      }

      lines.push("**Parameters**", "", ...renderParams(action), "");
      for (let index = 0; index < action.examples.length; index += 1) {
        lines.push(...renderExample(action, index), "");
      }
    }
  }

  lines.push("---", "", "Generated by `src/scripts/generateActionsDoc.ts`.", "");
  return lines.join("\n");
}

export function actionsDocPath(): string {
  const here = dirname(fileURLToPath(import.meta.url));
  return resolve(here, "..", "..", "docs", "ACTIONS.md");
}

function main(): void {
  const file = actionsDocPath();
  const rendered = renderActionsDoc();
  const check = process.argv.includes("--check");
  if (check) {
    let current = "";
    try {
      current = readFileSync(file, "utf-8").replace(/\r\n/g, "\n");
    } catch {
      process.stderr.write(`Missing generated action reference: ${file}\n`);
      process.exit(1);
    }
    if (current !== rendered) {
      process.stderr.write(`Action reference is out of date: ${file}\nRun: npm run docs:actions\n`);
      process.exit(1);
    }
    process.stdout.write(`Action reference is up to date (${rendered.split("\n").length} lines).\n`);
    return;
  }
  mkdirSync(dirname(file), { recursive: true });
  writeFileSync(file, rendered, "utf-8");
  process.stdout.write(`Wrote ${file}\n`);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main();
}
